const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('aisess', {
  spawn: (opts) => ipcRenderer.invoke('pty-spawn', opts),
  write: (id, data) => ipcRenderer.send('pty-write', { id, data }),
  resize: (id, cols, rows) => ipcRenderer.send('pty-resize', { id, cols, rows }),
  // Scorrimento nella history di tmux; null senza tmux (scorre xterm)
  scroll: (id, lines) => ipcRenderer.invoke('pty-scroll', { id, lines }),
  scrollTo: (id, fromBottom) => ipcRenderer.invoke('pty-scroll', { id, fromBottom }),
  scrollState: (id) => ipcRenderer.invoke('pty-scroll', { id }),
  captureShell: (id) => ipcRenderer.invoke('pty-capture-shell', { id }),
  kill: (id) => ipcRenderer.invoke('pty-kill', { id }),
  // Sessioni dentro tmux: riattacco e terminazione esplicita
  attach: (opts) => ipcRenderer.invoke('pty-attach', opts),
  terminate: (id) => ipcRenderer.invoke('pty-terminate', { id }),
  listLive: () => ipcRenderer.invoke('list-live-sessions'),
  setLabel: (id, label) => ipcRenderer.send('pty-set-label', { id, label }),
  setMeta: (id, meta) => ipcRenderer.send('pty-set-meta', { id, ...meta }),
  restorable: () => ipcRenderer.invoke('restorable-sessions'),
  discardRestorable: () => ipcRenderer.invoke('discard-restorable'),
  terminateSession: (session) => ipcRenderer.invoke('terminate-session', { session }),
  onData: (cb) => ipcRenderer.on('pty-data', (_e, v) => cb(v)),
  onExit: (cb) => ipcRenderer.on('pty-exit', (_e, v) => cb(v)),
  onAgentSignal: (cb) => ipcRenderer.on('agent-signal', (_e, v) => cb(v)),
  // Aggiornamento automatico (app/updater.js): stato, applica, rimanda
  updateState: () => ipcRenderer.invoke('update-state'),
  applyUpdate: () => ipcRenderer.invoke('update-apply'),
  dismissUpdate: () => ipcRenderer.invoke('update-dismiss'),
  onUpdateState: (cb) => ipcRenderer.on('update-state', (_e, v) => cb(v)),
  getDefaults: () => ipcRenderer.invoke('get-defaults'),
  checkDeps: () => ipcRenderer.invoke('check-deps'),
  getHistory: () => ipcRenderer.invoke('get-history'),
  getRecentDirs: (limit) => ipcRenderer.invoke('get-recent-dirs', { limit }),
  resolveProject: (cwd) => ipcRenderer.invoke('resolve-project', { cwd }),
  gitGraph: (cwd, limit) => ipcRenderer.invoke('git-graph', { cwd, limit }),
  gitBranches: (cwd) => ipcRenderer.invoke('git-branches', { cwd }),
  gitSwitch: (cwd, name, kind) => ipcRenderer.invoke('git-switch', { cwd, name, kind }),
  gitCreateBranch: (cwd, name) => ipcRenderer.invoke('git-create-branch', { cwd, name }),
  gitDeleteBranch: (cwd, name, force) => ipcRenderer.invoke('git-delete-branch', { cwd, name, force }),
  gitSessions: () => ipcRenderer.invoke('git-sessions'),
  saveGitSessions: (sessions) => ipcRenderer.invoke('git-sessions-save', { sessions }),
  gitChanges: (cwd, base, since) => ipcRenderer.invoke('git-changes', { cwd, base, since }),
  gitFileDiff: (cwd, base, path, since) => ipcRenderer.invoke('git-file-diff', { cwd, base, path, since }),
  gitSnapshot: (cwd) => ipcRenderer.invoke('git-snapshot', { cwd }),
  gitStaging: (cwd) => ipcRenderer.invoke('git-staging', { cwd }),
  gitStagingDiff: (cwd, path, side) => ipcRenderer.invoke('git-staging-diff', { cwd, path, side }),
  worktreeList: (root) => ipcRenderer.invoke('worktree-list', { root }),
  worktreeStart: (root) => ipcRenderer.invoke('worktree-start', { root }),
  worktreeCreate: (root, branch, base) => ipcRenderer.invoke('worktree-create', { root, branch, base }),
  worktreeMerge: (root, path) => ipcRenderer.invoke('worktree-merge', { root, path }),
  worktreeRemove: (root, path, branch, force) => ipcRenderer.invoke('worktree-remove', { root, path, branch, force }),
  listOpencode: (limit, dirs) => ipcRenderer.invoke('list-opencode-sessions', { limit, dirs }),
  listClaude: (limit) => ipcRenderer.invoke('list-claude-sessions', { limit }),
  listCodex: (limit) => ipcRenderer.invoke('list-codex-sessions', { limit }),
  listAntigravity: (limit) => ipcRenderer.invoke('list-antigravity-sessions', { limit }),
  searchConversations: (query, scope, allSnippets = false) => ipcRenderer.invoke('search-conversations', { query, scope, allSnippets }),
  exportConversation: (source, id) => ipcRenderer.invoke('export-conversation', { source, id }),
  listClaudeAccounts: () => ipcRenderer.invoke('list-claude-accounts'),
  addClaudeAccount: ({ name, apiKey }) => ipcRenderer.invoke('add-claude-account', { name, apiKey }),
  deleteClaudeAccount: (id) => ipcRenderer.invoke('delete-claude-account', { id }),
  getCommandProfiles: () => ipcRenderer.invoke('get-command-profiles'),
  saveCommandProfiles: (profiles) => ipcRenderer.invoke('save-command-profiles', { profiles }),
  resetCommandProfiles: () => ipcRenderer.invoke('reset-command-profiles'),
  pickCwd: () => ipcRenderer.invoke('dialog-cwd'),
  menuAction: (action) => ipcRenderer.invoke('menu-action', { action }),
  usage: (active, tab) => ipcRenderer.invoke('usage-snapshot', { active, tab }),
  listExtensions: (cwd) => ipcRenderer.invoke('list-extensions', { cwd }),
  clipboardWrite: (text) => ipcRenderer.invoke('clipboard-write', { text }),
  clipboardRead: () => ipcRenderer.invoke('clipboard-read'),
  // Notifiche di sistema (app/notify.js): il renderer dice chi ha finito, il main decide se mostrarla
  notifyFinished: (item) => ipcRenderer.send('notify-finished', item),
  notifyBadge: (count) => ipcRenderer.send('notify-badge', count),
  notifyConfig: (cfg) => ipcRenderer.invoke('notify-config', cfg),
  onNotifyOpenTab: (cb) => ipcRenderer.on('notify-open-tab', (_e, id) => cb(id)),
  onMenuEdit: (cb) => ipcRenderer.on('menu-edit', (_e, action) => cb(action)),
  onMenu: (channel, cb) => {
    const allowed = ['menu-new-session', 'menu-open-config', 'menu-term-font-bigger', 'menu-term-font-smaller', 'menu-term-font-reset', 'menu-type-colors', 'menu-pets', 'menu-changes', 'menu-notifications'];
    if (!allowed.includes(channel)) return;
    ipcRenderer.on(channel, () => cb());
  },
});
